#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn errors_say_their_names_and_domains_as_qt_does() {
        assert_eq!(name(-6), "net::ERR_FILE_NOT_FOUND");
        assert_eq!(domain(-6), 1);
        assert_eq!(name(-312), "net::ERR_UNSAFE_PORT");
        assert_eq!(domain(-312), 4);
        assert_eq!(name(-3), "net::ERR_ABORTED");
        assert_eq!(domain(-102), 2);
        assert_eq!(domain(-202), 3);
        assert_eq!(domain(-105), 2);
        assert_eq!(domain(-803), 6);
    }
}
