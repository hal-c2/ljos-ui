//! Chromium's network errors as `WebEngineLoadingInfo` says them: the
//! code, its name (`net::ERR_FILE_NOT_FOUND`) and the domain it is of.
//!
//! The names are those of Chromium's `net_error_list.h`, as CEF ships it
//! (`include/base/internal/cef_net_error_list.h`).

/// The name of network error `code`, with its `net::` prefix.
pub(crate) fn name(code: i32) -> String {
    let bare = NAMES
        .iter()
        .find(|(c, _)| *c == code)
        .map_or("ERR_FAILED", |(_, n)| n);
    format!("net::{bare}")
}

/// The `WebEngineLoadingInfo.ErrorDomain` of network error `code`, by the
/// range Chromium keeps it in.
pub(crate) fn domain(code: i32) -> i32 {
    match -code {
        100..=199 => 2,
        200..=299 => 3,
        300..=399 => 4,
        600..=699 => 5,
        800..=899 => 6,
        _ => 1,
    }
}

