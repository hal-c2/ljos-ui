    #[test]
    fn a_tsconfig_is_told_what_it_lacks() {
        assert_eq!(tsconfig_state(None), Tsconfig::Missing);
        assert_eq!(
            tsconfig_state(Some("{ \"compilerOptions\": {} }")),
            Tsconfig::NoBase
        );
        assert_eq!(
            tsconfig_state(Some(
                "{ // mine\n \"extends\": [\"a\", \"./.ljos/tsconfig.base.json\"], }"
            )),
            Tsconfig::Fine
        );
        let own = "{ \"extends\": \"./.ljos/tsconfig.base.json\", \"compilerOptions\": { \"rootDirs\": [\"src\"] } }";
        assert_eq!(tsconfig_state(Some(own)), Tsconfig::OwnRootDirs(64));
        let kept = "{ \"extends\": \"./.ljos/tsconfig.base.json\", \"compilerOptions\": { \"rootDirs\": [\"src\", \".\", \"./.ljos/types\"] } }";
        assert_eq!(tsconfig_state(Some(kept)), Tsconfig::Fine);
    }

    #[test]
    fn the_fix_keeps_comments_and_layout() {
        let fix =
            |text: Option<&str>| fix_tsconfig(text, "tsconfig.json").map(|f| (f.text, f.said));
        assert_eq!(
            fix(None),
            Some((
                "{\n  \"extends\": \"./.ljos/tsconfig.base.json\"\n}\n".into(),
                vec!["wrote tsconfig.json".into()]
            ))
        );
        assert_eq!(
            fix(Some("{\n  // The project's own options.\n  \"compilerOptions\": { \"strict\": true }\n}\n")).unwrap().0,
            "{\n  \"extends\": \"./.ljos/tsconfig.base.json\",\n  // The project's own options.\n  \"compilerOptions\": { \"strict\": true }\n}\n"
        );
        assert_eq!(
            fix(Some(
                "{\n  \"extends\": \"@tsconfig/strictest/tsconfig.json\"\n}\n"
            ))
            .unwrap()
            .0,
            "{\n  \"extends\": [\"@tsconfig/strictest/tsconfig.json\", \"./.ljos/tsconfig.base.json\"]\n}\n"
        );
        assert_eq!(
            fix(Some("{ \"extends\": [\"a\"] }")).unwrap().0,
            "{ \"extends\": [\"a\", \"./.ljos/tsconfig.base.json\"] }"
        );
        let own = fix(Some("{\n  \"extends\": \"./.ljos/tsconfig.base.json\",\n  \"compilerOptions\": { \"rootDirs\": [\"src\", \"gen\"] }\n}\n")).unwrap();
        assert_eq!(
            own.0,
            "{\n  \"extends\": \"./.ljos/tsconfig.base.json\",\n  \"compilerOptions\": { \"rootDirs\": [\"src\", \"gen\", \".\", \".ljos/types\"] }\n}\n"
        );
        assert_eq!(
            own.1,
            vec!["added \".\" and \".ljos/types\" to the rootDirs of tsconfig.json".to_owned()]
        );
        assert_eq!(
            fix(Some("{}")).unwrap().0,
            "{\n  \"extends\": \"./.ljos/tsconfig.base.json\"\n}"
        );
        assert_eq!(
            fix(Some("{ \"extends\": \"./.ljos/tsconfig.base.json\" }")),
            None
        );
        assert_eq!(fix(Some("not json")), None);
    }
