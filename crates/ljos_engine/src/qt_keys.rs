#[cfg(test)]
mod tests {
    use super::QT_KEY_ENUMS;

    #[test]
    fn the_documented_key_values() {
        let v = |k: &str| QT_KEY_ENUMS.iter().find(|(n, _)| *n == k).map(|(_, v)| *v);
        assert_eq!(v("Key_A"), Some(65));
        assert_eq!(v("Key_Escape"), Some(0x0100_0000));
        assert_eq!(v("Key_Return"), Some(0x0100_0004));
        assert_eq!(v("Key_Shift"), Some(0x0100_0020));
        assert_eq!(v("Key_F12"), Some(0x0100_003b));
        assert_eq!(v("TabFocusReason"), Some(1));
        assert_eq!(v("ApplicationShortcut"), Some(2));
    }

    #[test]
    fn no_key_is_listed_twice() {
        let mut names: Vec<&str> = QT_KEY_ENUMS.iter().map(|(n, _)| *n).collect();
        names.sort_unstable();
        let before = names.len();
        names.dedup();
        assert_eq!(before, names.len());
    }
}
