# Mesh helpers (glTF axes, millimetres)
# --------------------------------------------------------------------------
def lathe(bm, section, segments, mat, phase=0.0, closed=False, axis="Z"):
    """Spin an (r, h) section about the Z axis (h along Z) or the X axis
    (h along X). Points with r == 0 are on the axis."""
    def point(r, h, a):
        c, s = r * math.cos(a), r * math.sin(a)
        return (c, s, h) if axis == "Z" else (h, c, s)

    rings = []
    for r, h in section:
        if r == 0.0:
            v = bm.verts.new(point(0.0, h, 0.0))
            rings.append([v] * segments)
        else:
            rings.append([bm.verts.new(point(r, h, phase + 2 * math.pi * s / segments))
                          for s in range(segments)])
    pairs = list(zip(rings, rings[1:]))
    if closed:
        pairs.append((rings[-1], rings[0]))
    for a, b in pairs:
        for s in range(segments):
            s2 = (s + 1) % segments
            verts = []
            for v in (a[s], a[s2], b[s2], b[s]):
                if v not in verts:
                    verts.append(v)
            if len(verts) >= 3:
                bm.faces.new(verts).material_index = mat
    return rings


def hull(bm, points, mat):
    """The convex hull of `points`, as a closed solid."""
    verts = [bm.verts.new(p) for p in points]
    res = bmesh.ops.convex_hull(bm, input=verts)
    for f in {f for v in verts for f in v.link_faces}:
        f.material_index = mat
    for v in res.get("geom_interior", []):
        if isinstance(v, bmesh.types.BMVert):
            bm.verts.remove(v)
    # Coplanar triangles of a hull read as one facet.
    bmesh.ops.dissolve_limit(bm, angle_limit=math.radians(0.5),
                             verts=list(bm.verts), edges=list(bm.edges))
    return verts


def add_box(bm, centre, size, mat, rot=None):
    m = Matrix.Translation(centre)
    if rot is not None:
        m = m @ rot
    m = m @ Matrix.Diagonal((*size, 1.0))
    res = bmesh.ops.create_cube(bm, size=1.0, matrix=m)
    for f in {f for v in res["verts"] for f in v.link_faces}:
        f.material_index = mat


def prism_x(bm, outline, x0, x1, mat):
    """Extrude a closed (y, z) outline from x0 to x1."""
    a = [bm.verts.new((x0, y, z)) for y, z in outline]
    b = [bm.verts.new((x1, y, z)) for y, z in outline]
    n = len(outline)
    for i in range(n):
        j = (i + 1) % n
        bm.faces.new((a[i], a[j], b[j], b[i])).material_index = mat
    bm.faces.new(list(reversed(a))).material_index = mat
    bm.faces.new(b).material_index = mat


