def hex_rgb(h):
    # The hex is sRGB; Blender colour sockets are linear.
    def lin(c):
        c /= 255.0
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    return tuple(lin(int(h[i:i + 2], 16)) for i in (1, 3, 5))


def r4(v):
    return [round(c, 4) + 0.0 for c in v]


def metres(v):
    """A glTF point in millimetres -> rig.json metres."""
    return r4([c * MM for c in v])


