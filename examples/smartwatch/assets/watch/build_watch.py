def look_at(obj, target):
    d = Vector(target) - obj.location
    obj.rotation_euler = d.to_track_quat("-Z", "Y").to_euler()


def render(out):
    os.makedirs(out, exist_ok=True)
    scene = bpy.context.scene
    scene.render.engine = "BLENDER_EEVEE"
    scene.render.resolution_x = 1000
    scene.render.resolution_y = 1000
    scene.render.resolution_percentage = 100
    scene.view_settings.view_transform = "AgX"
    world = bpy.data.worlds.new("preview")
    if not world.node_tree:
        world.use_nodes = True
    bg = world.node_tree.nodes.get("Background")
    if bg:
        bg.inputs["Color"].default_value = (0.012, 0.014, 0.028, 1)
    scene.world = world

    def light(name, loc, energy, color, size):
        lamp = bpy.data.lights.new(name, "AREA")
        lamp.energy = energy
        lamp.color = color
        lamp.size = size
        o = bpy.data.objects.new(name, lamp)
        o.location = loc
        look_at(o, (0, 0, 0))
        scene.collection.objects.link(o)

    light("key", (0.15, -0.2, 0.2), 3, (1, 1, 1), 0.15)
    light("rim", (-0.2, 0.15, 0.1), 2, (1.0, 0.4, 0.9), 0.15)
    light("fill", (-0.2, -0.15, -0.05), 0.8, (0.5, 0.8, 1.0), 0.2)

    cam_data = bpy.data.cameras.new("cam")
    cam_data.lens = 70
    cam_data.clip_start = 0.001
    cam = bpy.data.objects.new("cam", cam_data)
    scene.collection.objects.link(cam)
    scene.camera = cam
    for name, loc in (("front", (0.0, -0.17, 0.0)),
                      ("three_quarter", (0.12, -0.12, 0.04)),
                      ("side", (0.17, -0.02, 0.01))):
        cam.location = loc
        look_at(cam, (0, 0, 0))
        scene.render.filepath = os.path.join(out, f"vakt_{name}.png")
        bpy.ops.render.render(write_still=True)


if __name__ == "__main__":
    os.makedirs(OUT_DIR, exist_ok=True)
    build()
    if RENDER_DIR:
        render(RENDER_DIR)
