def new_object(name, mesh, mats):
    for m in mats:
        mesh.materials.append(m)
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    return obj


def finish_mesh(name, bm, pivot=(0, 0, 0), sharp_deg=30.0, flat=False):
    """bm in glTF millimetres -> a Blender mesh about `pivot`."""
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-5)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.transform(TO_BLENDER @ Matrix.Translation(-Vector(pivot)))
    mesh = bpy.data.meshes.new(name)
    bm.to_mesh(mesh)
    bm.free()
    if flat:
        mesh.shade_flat()
    else:
        mesh.shade_smooth()
        mesh.set_sharp_from_angle(angle=math.radians(sharp_deg))
    return mesh


def blender_point(p):
    return TO_BLENDER @ Vector(p)


