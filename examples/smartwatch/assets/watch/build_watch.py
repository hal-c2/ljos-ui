def lug_strips():
    """Boxes on the lugs' outer faces, in the watch's frame."""
    out = []
    for sy, tag in ((1, "top"), (-1, "bottom")):
        for sx, side in ((1, "right"), (-1, "left")):
            out.append({"name": f"lug_{tag}_{side}",
                        "center": (sx * (LUG_X[1] + 0.03), sy * 19.6, -1.4),
                        "size": (0.08, 6.4, 0.32), "color": NEON_CYAN})
    return out


def ring_mesh(name, spec, mat, axis="Z"):
    bm = bmesh.new()
    ri, ro = spec["radius_inner"], spec["radius_outer"]
    h = spec.get("height", 0.16) / 2
    lathe(bm, [(ri, -h), (ro, -h), (ro, h), (ri, h)], 96, 0, closed=True, axis=axis)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.transform(TO_BLENDER)
    mesh = bpy.data.meshes.new(name)
    bm.to_mesh(mesh)
    bm.free()
    mesh.materials.append(mat)
    return mesh


def box_mesh(name, size, mat):
    bm = bmesh.new()
    bmesh.ops.create_cube(bm, size=1.0, matrix=Matrix.Diagonal((*size, 1.0)))
    bm.transform(TO_BLENDER)
    mesh = bpy.data.meshes.new(name)
    bm.to_mesh(mesh)
    bm.free()
    mesh.materials.append(mat)
    return mesh


