C_BODY, C_BEZEL, C_TICK, C_BACK = 0, 1, 2, 3


def build_case(mats):
    bm = bmesh.new()
    g0, g1 = GROOVE
    # The case: a 24-facet shell from the caseback to its top.
    section = [
        (0.0, BACK_Z), (15.5, BACK_Z), (18.6, BACK_Z + 0.35), (20.8, -4.3),
        (22.4, -3.3), (CASE_R, -2.7), (CASE_R, g0 - 0.15), (GROOVE_R, g0),
        (GROOVE_R, g1), (CASE_R, g1 + 0.15), (CASE_R, 2.3), (22.4, TOP_Z),
        (0.0, TOP_Z),
    ]
    lathe(bm, section, CASE_FACETS, C_BODY, phase=CASE_PHASE)
    # Caseback sensor window: a raised dark disc.
    lathe(bm, [(0.0, BACK_Z - 0.5), (9.0, BACK_Z - 0.5), (10.5, BACK_Z - 0.05),
               (10.5, BACK_Z + 0.1), (0.0, BACK_Z + 0.1)], 64, C_BACK)
    # The bezel ring, smooth, with a channel near its outer edge where the
    # edge light sits.
    bezel = [
        (17.95, TOP_Z - 0.05), (22.35, TOP_Z - 0.05), (22.35, 4.0), (22.0, 4.38),
        (21.98, 4.38), (21.98, 4.2), (21.52, 4.2), (21.52, 4.6), (21.2, BEZEL_TOP),
        (18.85, BEZEL_TOP), (18.2, 4.15), (17.95, 3.9),
    ]
    lathe(bm, bezel, 96, C_BEZEL, closed=True)
    # Twelve hour ticks on the bezel; twelve o'clock is wider.
    for i in range(12):
        a = math.pi / 2 - 2 * math.pi * i / 12
        w = 1.1 if i == 0 else 0.45
        rot = Matrix.Rotation(a, 4, "Z")
        add_box(bm, rot @ Vector((19.95, 0.0, BEZEL_TOP + 0.05)), (1.3, w, 0.14),
                C_TICK, rot)
    # Faceted lugs at 12 and 6 o'clock.
    for sy in (1, -1):
        for sx in (1, -1):
            xi, xo = LUG_X[0] * sx, LUG_X[1] * sx
            pts = []
            for y, top, bot in ((15.5, 2.7, -4.3), (21.0, 2.0, -3.9),
                                (25.6, -0.2, -2.7)):
                for x, z in ((xi, bot), (xo, bot), (xo, top - 1.1),
                             (xo - 0.9 * sx, top), (xi, top)):
                    pts.append((x, y * sy, z))
            lug = bmesh.new()
            hull(lug, pts, C_BODY)
            tmp = bpy.data.meshes.new("lug_tmp")
            lug.to_mesh(tmp)
            lug.free()
            bm.from_mesh(tmp)
            bpy.data.meshes.remove(tmp)
        # The spring bar the strap hangs on.
        lathe(bm, [(0.0, -LUG_X[0]), (BAR_R, -LUG_X[0]), (BAR_R, LUG_X[0]),
                   (0.0, LUG_X[0])], 16, C_TICK, axis="X")
        bm.verts.ensure_lookup_table()
        for v in bm.verts[-(16 * 2 + 2):]:
            v.co.y += BAR_Y * sy
            v.co.z += BAR_Z
    # Angular crown guards above and below the crown.
    for sy in (1, -1):
        pts = []
        for y in (3.6 * sy, 5.4 * sy):
            for x, z in ((21.5, -3.4), (25.0, -2.6), (25.6, -1.2), (25.6, 0.9),
                         (24.6, 2.1), (21.5, 2.6)):
                pts.append((x, y, z))
        pts += [(x, y * 1.18 + 0.0, z) for x, y, z in pts[:6] if x < 22]
        guard = bmesh.new()
        hull(guard, pts, C_BODY)
        tmp = bpy.data.meshes.new("guard_tmp")
        guard.to_mesh(tmp)
        guard.free()
        bm.from_mesh(tmp)
        bpy.data.meshes.remove(tmp)
    mesh = finish_mesh("case", bm, sharp_deg=12.0)
    return new_object("case", mesh, [mats["body"], mats["bezel"], mats["tick"],
                                     mats["back"]])


K_STEM, K_KNURL = 0, 1


def build_crown(mats):
    """Local to its pivot; spin axis along +X."""
    bm = bmesh.new()
    lathe(bm, [(0.0, -0.4), (1.3, -0.4), (1.3, 1.0), (2.3, 1.05), (2.3, 1.55),
               (0.0, 1.55)], 32, K_STEM, axis="X")
    # Knurled grip: a 30-tooth star outline lofted along X, chamfered ends.
    teeth = 30
    stations = [(1.85, 0.86), (2.15, 1.0), (4.95, 1.0), (5.3, 0.84)]
    rings = []
    for x, k in stations:
        ring = []
        for i in range(teeth * 2):
            a = math.pi * i / teeth
            r = (3.1 if i % 2 == 0 else 2.78) * k
            ring.append(bm.verts.new((x, r * math.cos(a), r * math.sin(a))))
        rings.append(ring)
    n = teeth * 2
    for a, b in zip(rings, rings[1:]):
        for i in range(n):
            j = (i + 1) % n
            bm.faces.new((a[i], a[j], b[j], b[i])).material_index = K_KNURL
    bm.faces.new(list(reversed(rings[0]))).material_index = K_KNURL
    # The end face carries a shallow inset disc.
    end = bm.faces.new(rings[-1])
    end.material_index = K_KNURL
    lathe(bm, [(0.0, 5.42), (1.9, 5.42), (2.1, 5.25), (0.0, 5.25)], 32, K_STEM,
          axis="X", closed=True)
    mesh = finish_mesh("crown", bm, sharp_deg=25.0)
    return new_object("crown", mesh, [mats["tick"], mats["crown"]])


def button_frame():
    a = math.radians(BUTTON_DEG)
    radial = Vector((math.cos(a), math.sin(a), 0.0))
    base = radial * 22.55 + Vector((0, 0, CROWN_Z))
    return base, radial, Matrix.Rotation(a, 4, "Z")


def build_button(mats):
    base, _radial, rot = button_frame()
    bm = bmesh.new()
    pts = []
    for x, hw, hz in ((-0.6, 3.0, 1.3), (1.2, 3.0, 1.3), (1.75, 2.55, 0.85)):
        for y, z in ((-hw, -hz), (hw, -hz), (hw, hz), (-hw, hz)):
            pts.append(rot @ Vector((x, y, z)))
    hull(bm, [tuple(p) for p in pts], 0)
    mesh = finish_mesh("button", bm, flat=True)
    return new_object("button", mesh, [mats["button"]])


def build_glass(mats):
    bm = bmesh.new()
    rows = 10
    sag = GLASS_APEX - GLASS_BASE
    section = []
    for i in range(rows + 1):
        t = i / rows
        r = GLASS_R * (1 - t)
        section.append((r if i < rows else 0.0, GLASS_BASE + sag * (1 - (1 - t) ** 2)))
    lathe(bm, section, 96, 0)
    mesh = finish_mesh("glass", bm, sharp_deg=60.0)
    return new_object("glass", mesh, [mats["glass"]])


def build_screen(mats):
    """A flat disc facing +Z; its UVs put the disc inscribed in the unit
    square, upright: (0.5, 0.5) at the centre, 12 o'clock at the top edge."""
    bm = bmesh.new()
    uv = bm.loops.layers.uv.new("UVMap")
    segs, rings = 96, 6
    centre = bm.verts.new((0.0, 0.0, SCREEN_Z))
    grid = []
    for k in range(1, rings + 1):
        r = SCREEN_R * k / rings
        grid.append([bm.verts.new((r * math.cos(2 * math.pi * s / segs),
                                   r * math.sin(2 * math.pi * s / segs), SCREEN_Z))
                     for s in range(segs)])
    for s in range(segs):
        s2 = (s + 1) % segs
        bm.faces.new((centre, grid[0][s], grid[0][s2]))
        for k in range(rings - 1):
            bm.faces.new((grid[k][s], grid[k + 1][s], grid[k + 1][s2], grid[k][s2]))
    for f in bm.faces:
        for loop in f.loops:
            co = loop.vert.co
            # Blender's V runs up; the exporter flips it to glTF's V-down,
            # where the image's top row is V = 0 and lands at 12 o'clock.
            loop[uv].uv = (0.5 + co.x / (2 * SCREEN_R), 0.5 + co.y / (2 * SCREEN_R))
    bm.normal_update()
    for f in bm.faces:
        if f.normal.z < 0:
            f.normal_flip()
    bm.transform(TO_BLENDER)
    mesh = bpy.data.meshes.new("screen")
    bm.to_mesh(mesh)
    bm.free()
    mesh.shade_flat()
    return new_object("screen", mesh, [mats["screen"]])


L_STRAP, L_SPINE, L_BARREL = 0, 1, 2


def build_link(mats):
    """One strap link, its hinge (pivot) at the origin, reaching along +Y."""
    bm = bmesh.new()
    hw = STRAP_W / 2
    # Hinge barrel across the width.
    lathe(bm, [(0.0, -hw + 0.6), (1.35, -hw + 0.6), (1.35, hw - 0.6), (0.0, hw - 0.6)],
          20, L_BARREL, axis="X")
    # The plate: chamfered all round.
    plate = []
    for y in (0.9, 5.7):
        for x, z in ((-hw, -1.1), (hw, -1.1), (hw, 0.6), (hw - 1.0, 1.25),
                     (-hw + 1.0, 1.25), (-hw, 0.6)):
            plate.append((x, y, z))
    sub = bmesh.new()
    hull(sub, plate, L_STRAP)
    tmp = bpy.data.meshes.new("plate_tmp")
    sub.to_mesh(tmp)
    sub.free()
    bm.from_mesh(tmp)
    bpy.data.meshes.remove(tmp)
    # A raised faceted spine down the middle, an arrow pointing out.
    spine = []
    for y, hx in ((1.3, 3.6), (4.4, 3.6), (5.4, 1.4)):
        for x, z in ((-hx, 1.0), (hx, 1.0), (hx - 0.9, 1.75), (-hx + 0.9, 1.75)):
            spine.append((x, y, z))
    sub = bmesh.new()
    hull(sub, spine, L_SPINE)
    tmp = bpy.data.meshes.new("spine_tmp")
    sub.to_mesh(tmp)
    sub.free()
    bm.from_mesh(tmp)
    bpy.data.meshes.remove(tmp)
    mesh = finish_mesh("link", bm, sharp_deg=30.0)
    return new_object("link", mesh, [mats["strap"], mats["spine"], mats["tick"]])


