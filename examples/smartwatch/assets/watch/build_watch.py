def build():
    reset_scene()
    mats = materials()
    case = build_case(mats)
    crown = build_crown(mats)
    button = build_button(mats)
    glass = build_glass(mats)
    screen = build_screen(mats)
    link = build_link(mats)

    for obj, name in ((case, "case"), (crown, "crown"), (button, "button"),
                      (glass, "glass"), (screen, "screen"), (link, "link")):
        export_part_file(obj, f"{name}.glb")

    # Assemble.
    root = bpy.data.objects.new("vakt", None)
    bpy.context.scene.collection.objects.link(root)
    for obj in (case, glass, screen):
        obj.parent = root
    crown.parent = root
    crown.location = blender_point(CROWN_PIVOT)
    base, _radial, _rot = button_frame()
    button.parent = root
    button.location = blender_point(base)

    strips = []

    def strip(obj, parent, loc):
        bpy.context.scene.collection.objects.link(obj)
        obj.parent = parent
        obj.location = loc
        strips.append(obj)

    strip(bpy.data.objects.new("edge_ring", ring_mesh("edge_ring", EDGE_RING,
                                                      mats["neon_cyan"])),
          root, blender_point(EDGE_RING["center"]))
    strip(bpy.data.objects.new("side_band", ring_mesh("side_band", SIDE_BAND,
                                                      mats["neon_cyan"])),
          root, blender_point(SIDE_BAND["center"]))
    strip(bpy.data.objects.new("crown_ring", ring_mesh("crown_ring", CROWN_RING,
                                                       mats["neon_magenta"], axis="X")),
          crown, blender_point(CROWN_RING["center"]))
    for spec in lug_strips():
        strip(bpy.data.objects.new(spec["name"], box_mesh(spec["name"], spec["size"],
                                                          mats["neon_cyan"])),
              root, blender_point(spec["center"]))

    # The straps: chains of the one link, each hinged on the one before.
    chains = {}
    for side, sy in (("top", 1), ("bottom", -1)):
        anchor = bpy.data.objects.new(f"strap_{side}", None)
        bpy.context.scene.collection.objects.link(anchor)
        anchor.parent = root
        anchor.location = blender_point((0.0, BAR_Y * sy, BAR_Z))
        # The bottom strap is the top one turned half round about the face
        # normal (glTF +Z, Blender -Y), so both curl the same way locally.
        anchor.rotation_euler = (0, -math.pi if sy < 0 else 0.0, 0)
        parent, chain = anchor, []
        for i in range(LINKS):
            o = bpy.data.objects.new(f"link_{side}_{i}", link.data)
            bpy.context.scene.collection.objects.link(o)
            o.parent = parent
            o.location = blender_point((0.0, LINK_PITCH if i else 0.0, 0.0))
            o.rotation_euler = (math.radians(REST_DEG), 0, 0)
            chain.append(o)
            parent = o
        chains[side] = (anchor, chain)
    bpy.data.objects.remove(link, do_unlink=True)

    # Animations (Blender axes: glTF X = Blender X, glTF Y = Blender Z).
    animate([crown], "crown_turn", 0, 0, 2 * math.pi, CROWN_FRAMES, "LINEAR")
    animate([o for _a, c in chains.values() for o in c], "strap_flex", 0, 0,
            math.radians(FLEX_DEG), FLEX_FRAMES, "BEZIER")
    animate([root], "turntable", 2, 0, 2 * math.pi, TURN_FRAMES, "LINEAR")
    bpy.context.preferences.edit.keyframe_new_interpolation_type = "BEZIER"
    bpy.context.scene.frame_set(0)

    everything = [root, case, glass, screen, crown, button] + strips + \
        [a for a, _c in chains.values()] + [o for _a, c in chains.values() for o in c]
    export(os.path.join(OUT_DIR, "watch.glb"), everything, True)
    write_rig(case, crown, button, glass, screen, chains)
    return root


def triangles(mesh):
    return sum(len(p.vertices) - 2 for p in mesh.polygons)


