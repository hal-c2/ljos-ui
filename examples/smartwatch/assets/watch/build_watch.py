"""Build the Vakt demo smartwatch from scratch and export it as glTF.

    blender -b --factory-startup --python build_watch.py [-- --out DIR] [--render DIR]

Everything here is generated in code: no imported meshes, images or
third-party assets. The output is the same on every run (no randomness,
fixed names, fixed export settings), so the files can be checked in and
regenerated byte for byte.

The geometry is written in glTF axes and millimetres, the way the app sees
the watch: +Z out of the face, +Y towards 12 o'clock, +X towards the crown at
3 o'clock. TO_BLENDER turns that into Blender's Z-up metres, and the glTF
exporter turns it back: glTF (x, y, z) = Blender (x, z, -y).
"""

