"""Build the Svala GT demo car from scratch and export it as glTF.

    blender -b --factory-startup --python build_car.py [-- --out DIR] [--render DIR]

Everything here is generated in code: no imported meshes, images or
third-party assets. The output is the same on every run (no randomness,
fixed names, fixed export settings), so the files can be checked in and
regenerated byte for byte.

Blender works Z-up with the car's front towards -Y and its left towards +X.
The glTF exporter converts to +Y up, front towards +Z, left still +X:
glTF (x, y, z) = Blender (x, z, -y).
"""

