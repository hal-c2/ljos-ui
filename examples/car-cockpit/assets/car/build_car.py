def new_object(name, mesh, mats):
    for m in mats:
        mesh.materials.append(m)
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    return obj


def mesh_from_bm(name, bm):
    mesh = bpy.data.meshes.new(name)
    bm.to_mesh(mesh)
    bm.free()
    return mesh


def apply_modifiers(obj):
    dg = bpy.context.evaluated_depsgraph_get()
    ev = obj.evaluated_get(dg)
    mesh = bpy.data.meshes.new_from_object(ev, preserve_all_data_layers=True,
                                           depsgraph=dg)
    old = obj.data
    name = old.name
    obj.modifiers.clear()
    obj.data = mesh
    bpy.data.meshes.remove(old)
    mesh.name = name


def smooth(mesh, angle=40.0):
    mesh.shade_smooth()
    mesh.set_sharp_from_angle(angle=math.radians(angle))


def drop_attribute(mesh, name):
    attr = mesh.attributes.get(name)
    if attr is not None:
        mesh.attributes.remove(attr)


