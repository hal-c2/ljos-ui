# Wheel
# --------------------------------------------------------------------------
def lathe(bm, section, segments, mat, hint_centre, closed=False):
    """Spin a (x, r) section round the X axis.

    Faces are turned to point away from hint_centre (x, r) in the section
    plane, so open sections still get outward normals.
    """
    rings = []
    for x, r in section:
        if r == 0.0:
            v = bm.verts.new((x, 0.0, 0.0))
            rings.append([v] * segments)
        else:
            rings.append([bm.verts.new((x, r * math.cos(2 * math.pi * s / segments),
                                        r * math.sin(2 * math.pi * s / segments)))
                          for s in range(segments)])
    pairs = list(zip(rings, rings[1:]))
    if closed:
        pairs.append((rings[-1], rings[0]))
    for a, b in pairs:
        for s in range(segments):
            s2 = (s + 1) % segments
            verts = []
            for v in (a[s], a[s2], b[s2], b[s]):
                if v not in verts:
                    verts.append(v)
            if len(verts) < 3:
                continue
            f = bm.faces.new(verts)
            f.material_index = mat
            f.normal_update()
            c = f.calc_center_median()
            radial = Vector((0.0, c.y, c.z))
            r = radial.length
            out = Vector((c.x - hint_centre[0], 0, 0)) + \
                radial.normalized() * (r - hint_centre[1])
            if f.normal.dot(out) < 0:
                f.normal_flip()
    return rings


def ring_section(cx, cr, radius, n):
    return [(cx + radius * math.cos(2 * math.pi * i / n),
             cr + radius * math.sin(2 * math.pi * i / n)) for i in range(n)]


W_TYRE, W_RIM, W_BRAKE, W_NEON = 0, 1, 2, 3


def build_wheel(mats):
    bm = bmesh.new()
    h = WHEEL_W / 2
    tyre = [(-h + 0.02, 0.272), (-h, 0.29), (-h, 0.34), (-h + 0.025, 0.365),
            (-h + 0.06, WHEEL_R), (h - 0.06, WHEEL_R), (h - 0.025, 0.365),
            (h, 0.34), (h, 0.29), (h - 0.02, 0.272)]
    lathe(bm, tyre, 64, W_TYRE, (0.0, 0.31))
    # Aero disc: a shallow dish from the hub out to the tyre bead.
    rim = [(h - 0.035, 0.0), (h - 0.03, 0.035), (h - 0.045, 0.06), (h - 0.075, 0.10),
           (h - 0.07, 0.20), (h - 0.045, 0.245), (h - 0.02, 0.262),
           (h - 0.02, 0.274), (-h + 0.03, 0.274)]
    lathe(bm, rim, 64, W_RIM, (-0.6, 0.0))
    brake = [(-0.03, 0.12), (-0.03, 0.225), (-0.055, 0.225), (-0.055, 0.12)]
    lathe(bm, brake, 48, W_BRAKE, (-0.0425, 0.17), closed=True)
    neon = ring_section(h - 0.022, 0.255, 0.006, 6)
    lathe(bm, neon, 64, W_NEON, (h - 0.022, 0.255), closed=True)
    # Turbine blades over the dish.
    for i in range(6):
        a = 2 * math.pi * i / 6
        rot = Matrix.Rotation(a, 4, "X") @ Matrix.Rotation(math.radians(18), 4, "Z")
        add_box(bm, rot @ Vector((h - 0.06, 0.0, 0.155)), (0.035, 0.02, 0.15),
                W_RIM, Matrix.Rotation(a, 4, "X") @ Matrix.Rotation(math.radians(18), 4, "Z"))
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-6)
    mesh = mesh_from_bm("wheel", bm)
    smooth(mesh, 40.0)
    return new_object("wheel", mesh, [mats["tyre"], mats["rim"], mats["brake"],
                                      mats["neon_cyan"]])


