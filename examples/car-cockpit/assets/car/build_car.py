def build():
    reset_scene()
    mats = materials()
    body_mats = [mats["paint"], mats["glass"], mats["trim"], mats["interior"]]

    loft = new_object("loft", build_loft(), body_mats)
    cut_arches(loft)

    hinge = features(-0.05)[I_P8]
    door_mid = (DOOR_Y[0] + DOOR_Y[1]) / 2
    port_pts = features(PORT_Y[0])
    port_z = (port_pts[I_P4B][1] + port_pts[I_P5][1]) / 2
    port_x = side_x(PORT_Y[0], port_z)
    pivots = {
        "body": Vector((0, 0, 0)),
        "door_left": Vector((hinge[0], door_mid, hinge[1])),
        "door_right": Vector((-hinge[0], door_mid, hinge[1])),
        "frunk": Vector((0, FRUNK_Y[1], features(FRUNK_Y[1])[I_P9][1])),
        "trunk": Vector((0, TRUNK_Y[0], features(TRUNK_Y[0])[I_P9][1])),
        "charge_port": Vector((port_x, PORT_Y[0], port_z)),
    }

    objs = {}
    for index, name in enumerate(PARTS):
        mesh = split_part(loft.data, index, name)
        mesh.transform(Matrix.Translation(-pivots[name]))
        obj = new_object(name, mesh, body_mats)
        obj.location = pivots[name]
        finish_panel(obj, bevel=0.006 if name != "charge_port" else 0.003)
        objs[name] = obj
    lmesh = loft.data
    bpy.data.objects.remove(loft, do_unlink=True)
    bpy.data.meshes.remove(lmesh)
    add_details(objs["body"])
    wheel = build_wheel(mats)

    # Part files first, before anything is parented or animated.
    for name in PARTS:
        export_part_file(objs[name], f"{name}.glb")
    export_part_file(wheel, "wheel.glb")

    # Assemble.
    root = bpy.data.objects.new("svala", None)
    bpy.context.scene.collection.objects.link(root)
    for name in PARTS:
        objs[name].parent = root
    wheels = {}
    for name, x, y in (("wheel_fl", TRACK_X, -AXLE_Y), ("wheel_fr", -TRACK_X, -AXLE_Y),
                       ("wheel_rl", TRACK_X, AXLE_Y), ("wheel_rr", -TRACK_X, AXLE_Y)):
        w = bpy.data.objects.new(name, wheel.data)
        bpy.context.scene.collection.objects.link(w)
        w.location = (x, y, WHEEL_R)
        if x < 0:
            # Right wheels are the left wheel turned round, not mirrored.
            w.rotation_euler = (0, 0, math.pi)
        w.parent = root
        wheels[name] = w
    bpy.data.objects.remove(wheel, do_unlink=True)

    strips = []
    for name, centre, size, colour, group in strip_specs(pivots):
        mat = mats["neon_magenta"] if group == "rear" else mats["neon_cyan"]
        obj = bpy.data.objects.new(name, box_mesh(name, size, mat))
        bpy.context.scene.collection.objects.link(obj)
        parent = objs[group] if group.startswith("door") else root
        obj.parent = parent
        obj.location = Vector(centre) - (pivots[group] if group in pivots else Vector())
        strips.append((obj, centre, size, colour, group))

    # Animations (Blender rotation axes; see rig.json for the glTF ones).
    r = math.radians
    animate(objs["door_left"], "door_left_open", 1, 0, -r(OPEN_DEG["door_left"]),
            OPEN_FRAMES, "BEZIER")
    animate(objs["door_right"], "door_right_open", 1, 0, r(OPEN_DEG["door_right"]),
            OPEN_FRAMES, "BEZIER")
    animate(objs["frunk"], "frunk_open", 0, 0, -r(OPEN_DEG["frunk"]), OPEN_FRAMES, "BEZIER")
    animate(objs["trunk"], "trunk_open", 0, 0, r(OPEN_DEG["trunk"]), OPEN_FRAMES, "BEZIER")
    animate(objs["charge_port"], "charge_port_open", 2, 0, -r(OPEN_DEG["charge_port"]),
            OPEN_FRAMES, "BEZIER")
    for name, w in wheels.items():
        sign = 1 if w.location.x > 0 else -1
        animate(w, "wheels_spin", 0, 0, sign * 2 * math.pi, SPIN_FRAMES, "LINEAR")
    bpy.context.preferences.edit.keyframe_new_interpolation_type = "BEZIER"
    bpy.context.scene.frame_set(0)

    car_objs = [root] + [objs[n] for n in PARTS] + list(wheels.values()) + \
        [s[0] for s in strips]
    export(os.path.join(OUT_DIR, "car.glb"), car_objs, True)

    write_rig(objs, pivots, wheels, strips)
    return objs, wheels, strips


def bbox(objs):
    lo = Vector((1e9, 1e9, 1e9))
    hi = -lo
    for o in objs:
        for c in o.bound_box:
            w = o.matrix_world @ Vector(c)
            lo = Vector(map(min, lo, w))
            hi = Vector(map(max, hi, w))
    return lo, hi


def triangles(mesh):
    return sum(len(p.vertices) - 2 for p in mesh.polygons)


def write_rig(objs, pivots, wheels, strips):
    bpy.context.view_layer.update()
    lo, hi = bbox(list(objs.values()) + list(wheels.values()))
    # glTF axis and degrees for each opening part. The sign is the
    # rotation about that +axis (right-hand rule) that opens the part.
    axes = {
        "door_left": ([0, 0, 1], +OPEN_DEG["door_left"]),
        "door_right": ([0, 0, 1], -OPEN_DEG["door_right"]),
        "frunk": ([1, 0, 0], -OPEN_DEG["frunk"]),
        "trunk": ([1, 0, 0], +OPEN_DEG["trunk"]),
        "charge_port": ([0, 1, 0], -OPEN_DEG["charge_port"]),
    }
    parts = [{
        "name": "body",
        "file": "body.glb",
        "node": "body",
        "pivot": gltf(pivots["body"]),
        "triangles": triangles(objs["body"].data),
    }]
    for name in PARTS[1:]:
        axis, angle = axes[name]
        parts.append({
            "name": name,
            "file": f"{name}.glb",
            "node": name,
            "pivot": gltf(pivots[name]),
            "axis": axis,
            "open_angle_deg": angle,
            "animation": f"{name}_open",
            "triangles": triangles(objs[name].data),
        })
    wheel_list = []
    for name, w in wheels.items():
        left = w.location.x > 0
        wheel_list.append({
            "name": name,
            "center": gltf(w.location),
            "side": "left" if left else "right",
            "rotation_deg": [0, 0, 0] if left else [0, 180, 0],
            "forward_spin_sign": 1 if left else -1,
        })
    strip_list = []
    for obj, centre, size, colour, group in strips:
        rel = Vector(centre) - (pivots[group] if group in pivots else Vector())
        strip_list.append({
            "name": obj.name,
            "group": group,
            "center": gltf(rel),
            "center_relative_to": group if group in pivots else "car",
            "size": [round(size[0], 4), round(size[2], 4), round(size[1], 4)],
            "color": colour,
            "emissive_strength": NEON_STRENGTH,
        })
    rig = {
        "name": "Svala GT",
        "generator": "build_car.py (Blender, headless)",
        "units": "metres",
        "axes": {"up": "+Y", "front": "+Z", "left": "+X", "handedness": "right"},
        "origin": "on the ground, centred between the axles",
        "dimensions": {
            "length": round(hi.y - lo.y, 3),
            "width": round(hi.x - lo.x, 3),
            "height": round(hi.z - lo.z, 3),
            "wheelbase": WHEELBASE,
            "bounds_min": gltf((lo.x, hi.y, lo.z)),
            "bounds_max": gltf((hi.x, lo.y, hi.z)),
        },
        "notes": [
            "Each part file holds one node at its own origin; that origin is "
            "the pivot. Place the file under a node at `pivot` and rotate that "
            "node about `axis` by up to `open_angle_deg` (right-hand rule, "
            "sign included) to open it.",
            "wheel.glb is a LEFT wheel, axle along X, outer face towards +X. "
            "Right wheels use the same file turned by `rotation_deg` (180 about Y). "
            "Rolling forward is a positive spin about the wheel's own X for left "
            "wheels and negative for right ones (`forward_spin_sign`).",
            "Light strips are not in the part files. Strips whose group names a "
            "door have `center` relative to that door's pivot and move with it; "
            "the rest are relative to the car origin. Boxes are axis-aligned.",
            "car.glb holds everything assembled under the node `svala`, with "
            "the strips and the named animations.",
        ],
        "parts": parts,
        "wheel": {
            "file": "wheel.glb",
            "node": "wheel",
            "radius": WHEEL_R,
            "width": WHEEL_W,
            "spin_axis": [1, 0, 0],
            "spin_deg_per_second": 360.0 * FPS / SPIN_FRAMES,
            "triangles": triangles(wheels["wheel_fl"].data),
            "positions": wheel_list,
        },
        "light_strips": strip_list,
        "animations": [
            {"name": f"{n}_open", "duration_s": OPEN_FRAMES / FPS, "loop": False,
             "nodes": [n]} for n in PARTS[1:]
        ] + [{"name": "wheels_spin", "duration_s": SPIN_FRAMES / FPS, "loop": True,
              "nodes": list(wheels)}],
        "materials": {
            "paint": f"candy violet {PAINT}, metallic 0.5, roughness 0.3",
            "glass": "gloss black canopy, roughness 0.12",
            "trim": "gloss black lower body, nose and tail, roughness 0.32",
            "neon_front_side": NEON_CYAN,
            "neon_rear": NEON_MAGENTA,
        },
    }
    with open(os.path.join(OUT_DIR, "rig.json"), "w", encoding="utf-8") as fh:
        json.dump(rig, fh, indent=2)
        fh.write("\n")


