def build_loft():
    bm = bmesh.new()
    part = bm.faces.layers.int.new("part")
    src = bm.faces.layers.int.new("src")
    rings = []
    for y in STATIONS:
        half = profile(y)
        pts = [(x, y, z) for x, z in half]
        pts += [(-half[i][0], y, half[i][1]) for i in range(HALF - 2, 0, -1)]
        rings.append([bm.verts.new(p) for p in pts])
    for i in range(len(STATIONS) - 1):
        ym = (STATIONS[i] + STATIONS[i + 1]) / 2
        a, b = rings[i], rings[i + 1]
        for k in range(RING):
            k2 = (k + 1) % RING
            left = k < HALF - 1
            row = k if left else RING - 1 - k
            f = bm.faces.new((a[k], a[k2], b[k2], b[k]))
            f[part] = part_of(row, left, ym)
            f[src] = 1
            f.material_index = material_of(row, ym)
    for ring in (rings[0], list(reversed(rings[-1]))):
        f = bm.faces.new(ring)
        f[part] = P_BODY
        f[src] = 1
        f.material_index = M_PAINT
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    return mesh_from_bm("loft", bm)


def build_arch_cutter():
    bm = bmesh.new()
    for y in (-AXLE_Y, AXLE_Y):
        for side in (1, -1):
            m = (Matrix.Translation((side * 0.95, y, ARCH_Z)) @
                 Matrix.Rotation(math.pi / 2, 4, "Y"))
            bmesh.ops.create_cone(bm, cap_ends=True, segments=40,
                                  radius1=ARCH_R, radius2=ARCH_R, depth=0.80,
                                  matrix=m)
    return mesh_from_bm("arch_cutter", bm)


def cut_arches(obj):
    cutter = bpy.data.objects.new("arch_cutter", build_arch_cutter())
    bpy.context.scene.collection.objects.link(cutter)
    mod = obj.modifiers.new("arches", "BOOLEAN")
    mod.operation = "DIFFERENCE"
    mod.solver = "EXACT"
    mod.object = cutter
    apply_modifiers(obj)
    mesh = cutter.data
    bpy.data.objects.remove(cutter, do_unlink=True)
    bpy.data.meshes.remove(mesh)
    # Faces the cutter made are the wheel wells: plain body trim.
    src = obj.data.attributes["src"].data
    part = obj.data.attributes["part"].data
    for poly in obj.data.polygons:
        if src[poly.index].value == 0:
            poly.material_index = M_TRIM
            part[poly.index].value = P_BODY


def split_part(loft_mesh, index, name):
    bm = bmesh.new()
    bm.from_mesh(loft_mesh)
    layer = bm.faces.layers.int["part"]
    doomed = [f for f in bm.faces if f[layer] != index]
    bmesh.ops.delete(bm, geom=doomed, context="FACES")
    if index != P_BODY:
        # Pull the panel's edge in so a thin shut-line shows round it.
        bm.verts.ensure_lookup_table()
        moves = []
        for v in bm.verts:
            if not v.is_boundary:
                continue
            centres = [f.calc_center_median() for f in v.link_faces]
            d = sum((c - v.co for c in centres), Vector()) / len(centres)
            # Keep the move in the surface: remove the normal component.
            n = v.normal
            d = d - n * d.dot(n)
            if d.length > 1e-6:
                moves.append((v, d.normalized() * PANEL_GAP))
        for v, d in moves:
            v.co += d
    return mesh_from_bm(name, bm)


def finish_panel(obj, bevel=0.006):
    smooth(obj.data, 35.0)
    sol = obj.modifiers.new("shell", "SOLIDIFY")
    sol.thickness = SHELL
    sol.offset = -1.0
    sol.use_rim = True
    sol.material_offset = M_INTERIOR
    sol.material_offset_rim = 0
    bev = obj.modifiers.new("bevel", "BEVEL")
    bev.limit_method = "ANGLE"
    bev.angle_limit = math.radians(25)
    bev.width = bevel
    bev.segments = 2
    wn = obj.modifiers.new("normals", "WEIGHTED_NORMAL")
    wn.keep_sharp = True
    apply_modifiers(obj)
    drop_attribute(obj.data, "part")
    drop_attribute(obj.data, "src")


def add_box(bm, centre, size, mat, rot=None):
    m = Matrix.Translation(centre)
    if rot is not None:
        m = m @ rot
    m = m @ Matrix.Diagonal((*size, 1.0))
    res = bmesh.ops.create_cube(bm, size=1.0, matrix=m)
    for f in {f for v in res["verts"] for f in v.link_faces}:
        f.material_index = mat


def add_details(obj):
    """Interior hint and static trim, added to the finished body mesh."""
    bm = bmesh.new()
    bm.from_mesh(obj.data)
    for x in (0.38, -0.38):
        add_box(bm, (x, 0.30, 0.30), (0.50, 0.55, 0.12), M_INTERIOR)
        add_box(bm, (x, 0.60, 0.62), (0.48, 0.12, 0.62), M_INTERIOR,
                Matrix.Rotation(math.radians(-18), 4, "X"))
    add_box(bm, (0, -0.55, 0.72), (1.70, 0.40, 0.14), M_INTERIOR)  # dash
    add_box(bm, (0, -0.05, 0.36), (0.22, 1.00, 0.20), M_INTERIOR)  # console
    add_box(bm, (0.38, -0.30, 0.80), (0.34, 0.04, 0.12), M_TRIM,
            Matrix.Rotation(math.radians(20), 4, "X"))  # yoke
    add_box(bm, (0, -2.22, 0.17), (1.60, 0.20, 0.025), M_TRIM)  # splitter
    for x in (-0.54, -0.27, 0.0, 0.27, 0.54):  # diffuser fins
        add_box(bm, (x, 2.14, 0.235), (0.015, 0.32, 0.05), M_TRIM)
    bm.to_mesh(obj.data)
    bm.free()


# --------------------------------------------------------------------------
# Wheel
# --------------------------------------------------------------------------
def lathe(bm, section, segments, mat, hint_centre, closed=False):
    """Spin a (x, r) section round the X axis.

    Faces are turned to point away from hint_centre (x, r) in the section
    plane, so open sections still get outward normals.
    """
    rings = []
    for x, r in section:
        if r == 0.0:
            v = bm.verts.new((x, 0.0, 0.0))
            rings.append([v] * segments)
        else:
            rings.append([bm.verts.new((x, r * math.cos(2 * math.pi * s / segments),
                                        r * math.sin(2 * math.pi * s / segments)))
                          for s in range(segments)])
    pairs = list(zip(rings, rings[1:]))
    if closed:
        pairs.append((rings[-1], rings[0]))
    for a, b in pairs:
        for s in range(segments):
            s2 = (s + 1) % segments
            verts = []
            for v in (a[s], a[s2], b[s2], b[s]):
                if v not in verts:
                    verts.append(v)
            if len(verts) < 3:
                continue
            f = bm.faces.new(verts)
            f.material_index = mat
            f.normal_update()
            c = f.calc_center_median()
            radial = Vector((0.0, c.y, c.z))
            r = radial.length
            out = Vector((c.x - hint_centre[0], 0, 0)) + \
                radial.normalized() * (r - hint_centre[1])
            if f.normal.dot(out) < 0:
                f.normal_flip()
    return rings


def ring_section(cx, cr, radius, n):
    return [(cx + radius * math.cos(2 * math.pi * i / n),
             cr + radius * math.sin(2 * math.pi * i / n)) for i in range(n)]


W_TYRE, W_RIM, W_BRAKE, W_NEON = 0, 1, 2, 3


def build_wheel(mats):
    bm = bmesh.new()
    h = WHEEL_W / 2
    tyre = [(-h + 0.02, 0.272), (-h, 0.29), (-h, 0.34), (-h + 0.025, 0.365),
            (-h + 0.06, WHEEL_R), (h - 0.06, WHEEL_R), (h - 0.025, 0.365),
            (h, 0.34), (h, 0.29), (h - 0.02, 0.272)]
    lathe(bm, tyre, 64, W_TYRE, (0.0, 0.31))
    # Aero disc: a shallow dish from the hub out to the tyre bead.
    rim = [(h - 0.035, 0.0), (h - 0.03, 0.035), (h - 0.045, 0.06), (h - 0.075, 0.10),
           (h - 0.07, 0.20), (h - 0.045, 0.245), (h - 0.02, 0.262),
           (h - 0.02, 0.274), (-h + 0.03, 0.274)]
    lathe(bm, rim, 64, W_RIM, (-0.6, 0.0))
    brake = [(-0.03, 0.12), (-0.03, 0.225), (-0.055, 0.225), (-0.055, 0.12)]
    lathe(bm, brake, 48, W_BRAKE, (-0.0425, 0.17), closed=True)
    neon = ring_section(h - 0.022, 0.255, 0.006, 6)
    lathe(bm, neon, 64, W_NEON, (h - 0.022, 0.255), closed=True)
    # Turbine blades over the dish.
    for i in range(6):
        a = 2 * math.pi * i / 6
        rot = Matrix.Rotation(a, 4, "X") @ Matrix.Rotation(math.radians(18), 4, "Z")
        add_box(bm, rot @ Vector((h - 0.06, 0.0, 0.155)), (0.035, 0.02, 0.15),
                W_RIM, Matrix.Rotation(a, 4, "X") @ Matrix.Rotation(math.radians(18), 4, "Z"))
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-6)
    mesh = mesh_from_bm("wheel", bm)
    smooth(mesh, 40.0)
    return new_object("wheel", mesh, [mats["tyre"], mats["rim"], mats["brake"],
                                      mats["neon_cyan"]])


