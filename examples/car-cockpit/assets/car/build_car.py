WHEEL_R = 0.37
WHEEL_W = 0.28
TRACK_X = 0.83  # wheel centre distance from the centre line
ARCH_R = 0.395
ARCH_Z = 0.36

FPS = 30
OPEN_FRAMES = 30  # every open animation lasts one second
SPIN_FRAMES = 30  # one wheel turn per second, loops

DOOR_Y = (-0.45, 0.72)
FRUNK_Y = (-1.95, -0.92)
TRUNK_Y = (0.80, 2.20)
PORT_Y = (1.95, 2.12)
PANEL_GAP = 0.005
SHELL = 0.02

# Neon colours (sRGB hex, as written to rig.json) and emission strength.
