def export(path, objects, animations):
    bpy.ops.object.select_all(action="DESELECT")
    for o in objects:
        o.select_set(True)
    bpy.context.view_layer.objects.active = objects[0]
    bpy.ops.export_scene.gltf(filepath=path, export_animations=animations, **EXPORT)


def export_part_file(obj, filename):
    """A part file: the part alone, its node at the origin (= its pivot)."""
    loc = obj.location.copy()
    obj.location = (0, 0, 0)
    export(os.path.join(OUT_DIR, filename), [obj], False)
    obj.location = loc


