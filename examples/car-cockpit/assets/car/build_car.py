def look_at(obj, target):
    d = Vector(target) - obj.location
    obj.rotation_euler = d.to_track_quat("-Z", "Y").to_euler()


def render(objs, out):
    os.makedirs(out, exist_ok=True)
    scene = bpy.context.scene
    scene.render.engine = "BLENDER_EEVEE"
    scene.render.resolution_x = 1280
    scene.render.resolution_y = 720
    scene.render.resolution_percentage = 100
    scene.render.film_transparent = False
    scene.view_settings.view_transform = "AgX"
    world = bpy.data.worlds.new("preview")
    world.color = (0.01, 0.012, 0.02)
    bg = world.node_tree.nodes.get("Background")
    if bg:
        bg.inputs["Color"].default_value = (0.012, 0.014, 0.028, 1)
        bg.inputs["Strength"].default_value = 1.0
    scene.world = world

    bm = bmesh.new()
    bmesh.ops.create_grid(bm, x_segments=1, y_segments=1, size=30)
    ground = bpy.data.objects.new("ground", mesh_from_bm("ground", bm))
    ground.data.materials.append(make_material("ground", (0.03, 0.03, 0.035), 0.0, 0.4))
    scene.collection.objects.link(ground)

    def light(name, loc, energy, color, size):
        l = bpy.data.lights.new(name, "AREA")
        l.energy = energy
        l.color = color
        l.size = size
        o = bpy.data.objects.new(name, l)
        o.location = loc
        look_at(o, (0, 0, 0.5))
        scene.collection.objects.link(o)

    light("key", (4, -4, 5), 2500, (1, 1, 1), 4)
    light("fill", (-5, -2, 3), 900, (0.6, 0.8, 1.0), 5)
    light("rim", (-2, 6, 3), 1500, (1.0, 0.4, 0.8), 5)
    light("top", (0, 0, 6), 800, (1, 1, 1), 6)

    cam_data = bpy.data.cameras.new("cam")
    cam_data.lens = 45
    cam = bpy.data.objects.new("cam", cam_data)
    scene.collection.objects.link(cam)
    scene.camera = cam
    shots = [
        ("front_three_quarter", (5.2, -6.2, 1.9), 0),
        ("rear_three_quarter", (-5.2, 6.2, 2.1), 0),
        ("open", (5.6, -5.0, 2.6), OPEN_FRAMES),
        ("open_rear", (5.4, 5.6, 2.6), OPEN_FRAMES),
    ]
    for name, loc, frame in shots:
        scene.frame_set(frame)
        cam.location = loc
        look_at(cam, (0, 0, 0.55))
        scene.render.filepath = os.path.join(out, f"svala_{name}.png")
        bpy.ops.render.render(write_still=True)
    scene.frame_set(0)


if __name__ == "__main__":
    os.makedirs(OUT_DIR, exist_ok=True)
    result = build()
    if RENDER_DIR:
        render(result[0], RENDER_DIR)
