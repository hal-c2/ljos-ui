def animate(obj, track, axis, start, end, frames, interpolation):
    bpy.context.preferences.edit.keyframe_new_interpolation_type = interpolation
    obj.rotation_mode = "XYZ"
    base = list(obj.rotation_euler)
    rot = list(base)
    rot[axis] = start
    obj.rotation_euler = rot
    obj.keyframe_insert("rotation_euler", index=axis, frame=0)
    rot[axis] = end
    obj.rotation_euler = rot
    obj.keyframe_insert("rotation_euler", index=axis, frame=frames)
    action = obj.animation_data.action
    action.name = f"{obj.name}_{track}"
    nla = obj.animation_data.nla_tracks.new()
    nla.name = track
    nla.strips.new(track, 0, action)
    obj.animation_data.action = None
    rot[axis] = start
    obj.rotation_euler = rot


